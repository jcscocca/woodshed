import { test, expect } from "@playwright/test";
import AxeBuilder from "@axe-core/playwright";
import { freshData } from "../../src/engine.js";
import { recordAttempt } from "../../src/program/progress.js";
import { SCALE_EXERCISES } from "../../src/program/scales.js";

const stateKey = "woodshed-state-v1";
const twoOctavePattern = "major:2";
const twoOctaveScale = SCALE_EXERCISES.find((exercise) => exercise.technique.pattern === "major" && exercise.technique.octaves === 2 && exercise.hands === "R");
const returnScale = SCALE_EXERCISES.find((exercise) => exercise.technique?.pattern === "major" && exercise.technique.octaves === 1 && exercise.hands === "R");
const ago = (days) => { const d = new Date(); d.setDate(d.getDate() - days); return `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, "0")}-${String(d.getDate()).padStart(2, "0")}`; };
const notes = (page) => page.getByRole("textbox", { name: "One thing to try next time", exact: true });
const minutes = (page) => page.getByRole("spinbutton", { name: "Minutes practised", exact: true });
const openCard = (page, exercise) => page.locator(".pg-scale-path .pg-card").filter({ has: page.getByRole("heading", { name: exercise.title, exact: true }) }).getByRole("button", { name: "Open lesson", exact: true }).click();
const goToScales = async (page) => {
  await page.getByRole("button", { name: "Scales", exact: true }).click();
  await page.getByRole("button", { name: "All-key reference", exact: true }).click();
  await expect(page.getByRole("region", { name: "All-key reference", exact: true })).toBeVisible();
};

test.beforeEach(async ({ page }) => {
  const errors = [];
  page.on("pageerror", (error) => errors.push(error.message));
  page.__scaleErrors = errors;
});
test.afterEach(async ({ page }) => expect(page.__scaleErrors).toEqual([]));

test("optional reference keeps pattern, key and drafts without becoming another guided course", async ({ page }) => {
  expect(twoOctaveScale).toBeTruthy();
  await page.goto("./"); await goToScales(page);
  const patternControl=page.getByRole("combobox", { name: "Pattern and range", exact: true });
  await expect(patternControl).toHaveAccessibleName("Pattern and range");
  await expect(page.locator("label").filter({has:patternControl})).toContainText("Pattern and range");
  await page.getByRole("combobox", { name: "Pattern and range", exact: true }).selectOption(twoOctavePattern);
  await page.getByRole("combobox", { name: "Scale key", exact: true }).selectOption(twoOctaveScale.key);
  await expect(page.locator("#ws-main .ws-main")).toHaveCSS("opacity", "1");
  const accessibility = await new AxeBuilder({ page }).withTags(["wcag2a", "wcag2aa", "wcag21a", "wcag21aa"]).analyze();
  expect(accessibility.violations.map((violation) => ({ id: violation.id, nodes: violation.nodes.map((node) => node.target) }))).toEqual([]);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= document.documentElement.clientWidth)).toBe(true);
  await openCard(page, twoOctaveScale);
  await expect(page.getByRole("img", { name: `Written score for ${twoOctaveScale.title}`, exact: true }).first()).toBeVisible();
  await expect(page.getByRole("slider", { name: /^Practice tempo/ })).toBeEnabled();
  await expect(page.getByLabel("From bar", { exact: true })).toHaveAccessibleName(/^From\b/);
  await expect(page.getByLabel("Through bar", { exact: true })).toHaveAccessibleName(/^Through\b/);
  await expect(page.getByLabel("What did you actually play?", { exact: true })).toHaveAccessibleName("What did you actually play?");
  await page.getByLabel("Through bar", { exact: true }).selectOption("2");
  await page.getByLabel("Repeat the excerpt", { exact: true }).check();
  await minutes(page).fill("1"); await notes(page).fill("CI scale fixture: keep the continuation crossing quiet; no piano performance measured.");
  await page.getByRole("button", { name: "Progress", exact: true }).click();
  await goToScales(page);
  await expect(page.getByRole("combobox", { name: "Pattern and range", exact: true })).toHaveValue(twoOctavePattern);
  await expect(page.getByRole("combobox", { name: "Scale key", exact: true })).toHaveValue(twoOctaveScale.key);
  await openCard(page, twoOctaveScale);
  await expect(notes(page)).toHaveValue("CI scale fixture: keep the continuation crossing quiet; no piano performance measured.");
  await expect(page.getByLabel("Through bar", { exact: true })).toHaveValue("2");
  await expect(page.getByLabel("Repeat the excerpt", { exact: true })).toBeChecked();
  await page.reload(); await goToScales(page);
  await expect(page.getByRole("combobox", { name: "Pattern and range", exact: true })).toHaveValue(twoOctavePattern);
  await expect(page.getByRole("combobox", { name: "Scale key", exact: true })).toHaveValue(twoOctaveScale.key);
  await openCard(page, twoOctaveScale);
  await expect(notes(page)).toHaveValue("CI scale fixture: keep the continuation crossing quiet; no piano performance measured.");
  await expect(minutes(page)).toHaveValue("1");
  await expect(page.getByLabel("Through bar", { exact: true })).toHaveValue("2");
  await page.getByRole("button", { name: "Save practice", exact: true }).click();
  await expect(page.locator(".pg-notice")).toContainText(`Saved: ${twoOctaveScale.title}`);
  const stored = await page.evaluate((key) => JSON.parse(localStorage.getItem(key)), stateKey);
  expect(stored.programProgress.attempts).toHaveLength(1);
  expect(stored.programProgress.attempts[0]).toMatchObject({ exerciseId: twoOctaveScale.id, section: "scales", minutes: 1, fromBar: 1, toBar: 2 });
  expect(stored.programProgress.attempts[0].sessionId).toBeUndefined();
  expect(stored.programProgress.completedBlocks).toEqual({});
  await openCard(page, twoOctaveScale);
  await expect(page.getByLabel("Through bar", { exact: true })).toHaveValue("2");
  await expect(page.getByRole("button", { name: "Right hand", exact: true })).toHaveAttribute("aria-pressed", "true");
  await page.getByRole("button", { name: "Close lesson", exact: true }).click();
  await page.getByRole("button", { name: "Progress", exact: true }).click();
  await expect(page.getByText("0/80", { exact: true })).toBeVisible();
  await expect(page.locator(".pg-history")).toContainText(twoOctaveScale.title);
  await expect(page.getByRole("region", { name: "Continuing scales progress", exact: true })).toHaveCount(0);
  await expect(page.getByRole("region", { name: "Guided bridge progress", exact: true })).toHaveCount(0);
  await expect(page.getByText("CI scale fixture: keep the continuation crossing quiet; no piano performance measured.", { exact: true })).toBeVisible();
});

test("a scale return preserves its first scope and difficult result after a successful repair", async ({ page }) => {
  expect(returnScale).toBeTruthy();
  const state = freshData();
  state.programProgress = recordAttempt(state.programProgress, { exerciseId: returnScale.id, section: "scales", date: ago(4), assessment: "ready", minutes: 3, bpm: 44, hands: "R", fromBar: 1, toBar: 2, note: "CI return fixture: a small crossing before playback." });
  await page.addInitScript(({ key, state }) => { if (!localStorage.getItem(key)) localStorage.setItem(key, JSON.stringify(state)); }, { key: stateKey, state });
  await page.goto("./"); await goToScales(page);
  await page.getByRole("region", { name: "Scale return checks", exact: true }).getByRole("button", { name: "Start return check", exact: true }).click();
  await expect(page.getByRole("heading", { name: returnScale.title, exact: true })).toBeVisible();
  await expect(page.getByLabel("Through bar", { exact: true })).toHaveValue("2");
  await expect(page.getByRole("slider", { name: /^Practice tempo/ })).toHaveValue("44");
  await page.getByRole("button", { name: "Needs more work", exact: true }).click();
  await page.getByLabel("Through bar", { exact: true }).selectOption("1");
  await page.getByRole("radio", { name: "Ready for a fresh check", exact: true }).check();
  await minutes(page).fill("1"); await notes(page).fill("CI return fixture: repair felt steadier; retain the first result.");
  await page.getByRole("button", { name: "Progress", exact: true }).click();
  await goToScales(page);
  await page.getByRole("region", { name: "Scale return checks", exact: true }).getByRole("button", { name: "Start return check", exact: true }).click();
  await expect(page.getByText("First return: needs more work.", { exact: false })).toBeVisible();
  await expect(page.getByText("Reported before playback.", { exact: false })).toBeVisible();
  await expect(page.getByLabel("Through bar", { exact: true })).toHaveValue("1");
  await expect(page.getByRole("radio", { name: "Ready for a fresh check", exact: true })).toBeChecked();
  await page.getByRole("button", { name: "Save practice", exact: true }).click();
  await expect(page.locator(".pg-notice")).toContainText("Review saved");
  const stored = await page.evaluate((key) => JSON.parse(localStorage.getItem(key)), stateKey);
  const saved = stored.programProgress.attempts.find((attempt) => attempt.section === "review");
  expect(saved).toMatchObject({ exerciseId: returnScale.id, assessment: "ready", fromBar: 1, toBar: 1, reviewCheck: { assessment: "practising", beforeDemo: true, hands: "R", bpm: 44, fromBar: 1, toBar: 2 } });
  expect(saved.sessionId).toBeUndefined(); expect(saved.reviewForSession).toBeUndefined();
  expect(stored.programProgress.completedBlocks).toEqual({});
  await page.reload(); await page.getByRole("button", { name: "Progress", exact: true }).click();
  await expect(page.getByText("0/80", { exact: true })).toBeVisible();
  await expect(page.getByText(/First return before playback: needed more work/)).toBeVisible();
});
